let fileContent = fs.readFileSync(targetPath, 'utf8');

let updatedCount = 0;

Object.entries(ARABIC_DATA).forEach(([slug, arObj]) => {
  const slugMarker = `slug: '${slug}'`;
  const idx = fileContent.indexOf(slugMarker);
  if (idx !== -1) {
    const postSnippet = fileContent.slice(idx, idx + 500);
    if (!postSnippet.includes('titleAr:')) {
      const commaMatch = fileContent.slice(idx + slugMarker.length).match(/^\s*,/);
      const skipLen = commaMatch ? commaMatch[0].length : 0;
      const insertion = `,\n    titleAr: ${JSON.stringify(arObj.titleAr)},` +
        `\n    excerptAr: ${JSON.stringify(arObj.excerptAr)},` +
        `\n    tagsAr: ${JSON.stringify(arObj.tagsAr)},` +
        `\n    contentAr: ${JSON.stringify(arObj.contentAr, null, 6).replace(/\n/g, '\n    ')},`;
      
      fileContent = fileContent.slice(0, idx + slugMarker.length) + insertion + fileContent.slice(idx + slugMarker.length + skipLen);
      updatedCount++;
    }
  }
});

console.log(`Successfully updated ${updatedCount} posts with Arabic translations!`);
fs.writeFileSync(targetPath, fileContent, 'utf8');
